/**
 * Writes src/components/CnIcon/mdiPaths.js: the @mdi/js path of every icon a
 * source file asks for with `mdiIcon('<Name>')`. Run it after adding an icon to
 * one of the lookup tables; tests/components/mdiIcon.spec.js fails while the
 * file is stale.
 *
 *   node scripts/generate-mdi-paths.mjs
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const mdi = require('@mdi/js')

/**
 * Every source file under a directory.
 *
 * @param {string} dir Directory to walk.
 * @return {string[]} Absolute .js / .vue paths.
 */
function walk(dir) {
	return readdirSync(dir).flatMap((entry) => {
		const full = join(dir, entry)
		if (statSync(full).isDirectory()) {
			return walk(full)
		}
		return /\.(js|vue)$/.test(entry) ? [full] : []
	})
}

const names = new Set()
for (const file of walk(join(root, 'src'))) {
	for (const match of readFileSync(file, 'utf8').matchAll(/\bmdiIcon\('([A-Za-z0-9]+)'\)/g)) {
		names.add(match[1])
	}
}

const missing = [...names].filter((name) => typeof mdi[`mdi${name}`] !== 'string')
if (missing.length > 0) {
	console.error(`Not in @mdi/js: ${missing.join(', ')}`)
	process.exit(1)
}

const lines = [...names].sort().map((name) => `\t${name}: '${mdi[`mdi${name}`]}',`)
writeFileSync(join(root, 'src/components/CnIcon/mdiPaths.js'), `// SPDX-FileCopyrightText: 2026 Conduction B.V.
// SPDX-License-Identifier: EUPL-1.2
// Generated by scripts/generate-mdi-paths.mjs from @mdi/js ${require('@mdi/js/package.json').version}. Do not edit.

/**
 * SVG path per MDI name, for the icons src/ creates with mdiIcon().
 *
 * @type {Readonly<Record<string, string>>}
 */
export const MDI_PATHS = Object.freeze({
${lines.join('\n')}
})
`)
console.log(`mdiPaths.js: ${names.size} icons`)
